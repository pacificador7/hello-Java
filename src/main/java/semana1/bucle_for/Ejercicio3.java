package semana1.bucle_for;

public class Ejercicio3 {
    public static void main(String[] args) {

        for (int i = 1; i <= 20; i++) {
            if (i % 2 == 0) {
                System.out.println(i);
            }
            /**
             * Este imprime los numeros que son pares, use un if para validar
             * que cada numero al dividirlo entre 2 no tuviera residuo usando modulo.
             */
        }
    }
}
